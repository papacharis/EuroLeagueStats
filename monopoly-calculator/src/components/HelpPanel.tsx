function Seq({ children }: { children: string }) {
  return (
    <span className="inline-flex flex-wrap gap-1 align-middle">
      {children.split(' ').map((k, i) => (
        <kbd key={i} className="kbd">
          {k}
        </kbd>
      ))}
    </span>
  );
}

